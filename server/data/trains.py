def search_trains(query: str, limit: int = 20):
    """Search trains by number or name."""
    q = query.lower()
    results = [
        t for t in trains
        if q in t["number"].lower()
        or q in t["name"].lower()
        or q in t["type"].lower()
    ]
    return results[:limit]


def get_all_trains():
    """Get all trains."""
    return trains


def get_trains_by_type(train_type: str):
    """Get trains filtered by type."""
    return [t for t in trains if t["type"].lower() == train_type.lower()]


def get_trains_at_station(station_code: str):
    """Get all trains that pass through a given station."""
    return [
        t for t in trains
        if any(s["station"] == station_code for s in t["route"])
    ]


def get_trains_between_stations(from_code: str, to_code: str):
    """
    Get all trains that pass through both stations in order (from → to).
    Returns list of train dicts with the relevant portion of route info.
    """
    results = []
    from_code = from_code.upper()
    to_code = to_code.upper()

    for train in trains:
        route = train["route"]
        station_codes = [s["station"] for s in route]

        if from_code in station_codes and to_code in station_codes:
            from_idx = station_codes.index(from_code)
            to_idx = station_codes.index(to_code)

            # Only include if 'from' comes before 'to' in route
            if from_idx < to_idx:
                segment = route[from_idx:to_idx + 1]
                segment_distance = segment[-1]["km"] - segment[0]["km"]
                results.append({
                    "train": train,
                    "from_station": from_code,
                    "to_station": to_code,
                    "from_index": from_idx,
                    "to_index": to_idx,
                    "segment": segment,
                    "segment_distance": segment_distance,
                })

    return results

